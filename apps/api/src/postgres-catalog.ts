import { createHash, randomUUID } from 'node:crypto';
import { DatabaseSync } from 'node:sqlite';
import type { Pool, PoolClient } from 'pg';
import type { CatalogEvent, Category, EventDetails, EventPage, EventStatus, Subscription } from '@afisha/contracts';
import {
  categories, categoriesSql, detailsOf, eventIdentity, mergeEventDetails, normalizeText, relevance, validateEvent,
} from './catalog.ts';
import type { CatalogStore, EventFilters, ImportReport, SourceEvent } from './catalog.ts';

const schema = `
CREATE TABLE IF NOT EXISTS events (
  id text PRIMARY KEY, identity text NOT NULL UNIQUE, title text NOT NULL, search_text text NOT NULL,
  city text NOT NULL, city_key text NOT NULL, venue text NOT NULL, venue_key text NOT NULL,
  category text NOT NULL CHECK (category IN ${categoriesSql}), starts_at text NOT NULL, ends_at text,
  price_min double precision, age_limit integer, status text NOT NULL CHECK (status IN ('published','draft','cancelled')),
  status_override text CHECK (status_override IN ('published','draft','cancelled')), details jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS events_schedule ON events(status, starts_at, id);
CREATE INDEX IF NOT EXISTS events_city_schedule ON events(city_key, status, starts_at, id);
CREATE TABLE IF NOT EXISTS sources (
  source_key text PRIMARY KEY, event_id text NOT NULL REFERENCES events(id), name text NOT NULL,
  url text NOT NULL, type text NOT NULL CHECK (type IN ('api','scrape','import','manual')),
  hash text NOT NULL, verified_at text, normalized jsonb NOT NULL, raw jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS sources_event ON sources(event_id);
CREATE TABLE IF NOT EXISTS audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_id text NOT NULL REFERENCES events(id),
  actor text NOT NULL, action text NOT NULL, recorded_at text NOT NULL, details jsonb NOT NULL
);
CREATE TABLE IF NOT EXISTS subscriptions (
  subscriber text NOT NULL, city text NOT NULL, category text NOT NULL CHECK (category IN ${categoriesSql}),
  PRIMARY KEY (subscriber, city, category)
);
CREATE TABLE IF NOT EXISTS catalog_migrations (name text PRIMARY KEY);
`;

type EventRow = { id: string; title: string; search_text: string; status: EventStatus; details: EventDetails };
type CanonicalRow = { id: string; identity: string; status_override: EventStatus | null };
type SourceRow = { event_id: string; name: string; url: string; verified_at: string | null };
const values = (count: number) => Array.from({ length: count }, (_, index) => '$' + (index + 1)).join(', ');
const columns = 'id, title, search_text, status, details';
const lockCatalog = 'SELECT pg_advisory_xact_lock(211505001)';

async function transaction<Result>(pool: Pool, work: (client: PoolClient) => Promise<Result>): Promise<Result> {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await work(client);
    await client.query('COMMIT');
    return result;
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

export async function initializeCatalog(pool: Pool) {
  await transaction(pool, async client => {
    await client.query(lockCatalog);
    await client.query(schema);
  });
}

// Preserve event IDs, provenance, status overrides and subscriptions across the one-time migration.
export async function migrateSqliteCatalog(pool: Pool, filename: string) {
  return transaction(pool, async client => {
    await client.query(lockCatalog);
    if ((await client.query("SELECT 1 FROM catalog_migrations WHERE name = 'sqlite-v1'")).rowCount) return;
    if ((await client.query('SELECT 1 FROM events LIMIT 1')).rowCount) {
      throw new Error('The PostgreSQL catalog already contains events. Migrate into an empty database.');
    }
    const sqlite = new DatabaseSync(filename, { readOnly: true });
    try {
      if (sqlite.prepare('PRAGMA user_version').get()?.user_version !== 1) throw new Error('Unsupported SQLite catalog schema.');
      sqlite.exec('BEGIN');
      for (const table of ['events', 'sources', 'audit_log', 'subscriptions']) {
        const insert = sqlite.prepare(`SELECT * FROM ${table}`);
        const columns = insert.columns().map(column => column.name);
        const rows = insert.all();
        for (let offset = 0; offset < rows.length; offset += 100) {
          const parameters = rows.slice(offset, offset + 100).flatMap(row => columns.map(column => row[column]));
          const tuples = Array.from({ length: parameters.length / columns.length }, (_, index) =>
            '(' + columns.map((_, column) => '$' + (index * columns.length + column + 1)).join(', ') + ')');
          await client.query(`INSERT INTO ${table} (${columns.join(', ')}) VALUES ${tuples.join(', ')}`, parameters);
        }
      }
      await client.query("SELECT setval(pg_get_serial_sequence('audit_log', 'id'), COALESCE(MAX(id), 1), MAX(id) IS NOT NULL) FROM audit_log");
      await client.query("INSERT INTO catalog_migrations(name) VALUES ('sqlite-v1')");
    } finally {
      sqlite.close();
    }
  });
}

export function openPostgresCatalog(pool: Pool, clock = () => new Date()): CatalogStore {
  async function eventCards(rows: EventRow[]): Promise<CatalogEvent[]> {
    if (!rows.length) return [];
    const { rows: sources } = await pool.query<SourceRow>(`SELECT DISTINCT ON (event_id, url) event_id, name, url, verified_at
      FROM sources WHERE event_id = ANY($1::text[]) AND (normalized->>'status' != 'draft' OR NOT EXISTS
        (SELECT 1 FROM sources AS visible WHERE visible.event_id = sources.event_id AND visible.normalized->>'status' != 'draft'))
      ORDER BY event_id, url, verified_at DESC NULLS LAST, source_key`, [rows.map(row => row.id)]);
    const byEvent = new Map<string, CatalogEvent['sources']>();
    for (const source of sources) {
      const group = byEvent.get(source.event_id) ?? [];
      group.push({ name: source.name, url: source.url, verifiedAt: source.verified_at ?? undefined });
      byEvent.set(source.event_id, group);
    }
    return rows.map(row => ({
      ...row.details, id: row.id, status: row.status,
      sources: (byEvent.get(row.id) ?? []).sort((first, second) =>
        (second.verifiedAt ?? '').localeCompare(first.verifiedAt ?? '') || first.url.localeCompare(second.url)),
    }));
  }

  async function writeEvent(client: PoolClient, id: string, identity: string, event: EventDetails) {
    const fields = ['identity', 'title', 'search_text', 'city', 'city_key', 'venue', 'venue_key', 'category',
      'starts_at', 'ends_at', 'price_min', 'age_limit', 'status', 'details'];
    await client.query(`INSERT INTO events (id, ${fields.join(', ')}) VALUES (${values(fields.length + 1)})
      ON CONFLICT(id) DO UPDATE SET ${fields.map(field => field + '=excluded.' + field).join(', ')}`, [
      id, identity, event.title, normalizeText([event.title, event.city, event.venue, event.description, event.language].filter(Boolean).join(' ')),
      event.city, normalizeText(event.city), event.venue, normalizeText(event.venue), event.category,
      event.startsAt, event.endsAt, event.priceMin, event.ageLimit, event.status, JSON.stringify(event),
    ]);
  }

  async function rebuild(client: PoolClient, id: string, identity: string, override: EventStatus | null) {
    const { rows } = await client.query<{ normalized: EventDetails }>(`SELECT normalized FROM sources WHERE event_id = $1
      ORDER BY CASE type WHEN 'manual' THEN 0 WHEN 'api' THEN 1 WHEN 'import' THEN 2 ELSE 3 END,
      verified_at DESC NULLS LAST, source_key`, [id]);
    await writeEvent(client, id, identity, mergeEventDetails(rows.map(row => row.normalized), override));
  }

  function change(client: PoolClient, id: string, actor: string, action: string, details: unknown) {
    return client.query('INSERT INTO audit_log (event_id, actor, action, recorded_at, details) VALUES ($1, $2, $3, $4, $5)',
      [id, actor, action, clock().toISOString(), JSON.stringify(details)]);
  }

  async function importEvents(events: readonly SourceEvent[], actor = 'import'): Promise<ImportReport> {
    return transaction(pool, async client => {
      await client.query(lockCatalog);
      const report: ImportReport = { added: 0, updated: 0, unchanged: 0, rejected: [] };
      for (const [index, input] of events.entries()) {
        let event: SourceEvent;
        let raw: string;
        try {
          event = validateEvent(input);
          raw = JSON.stringify(event.raw ?? null);
        } catch (error) {
          report.rejected.push({ row: index + 1, reason: error instanceof Error ? error.message : 'Некорректная запись.' });
          continue;
        }
        const identity = eventIdentity(event);
        const sourceKey = `${event.sourceType}:${event.sourceKey}`;
        const { rows: [source] } = await client.query<{ event_id: string; hash: string }>(
          'SELECT event_id, hash FROM sources WHERE source_key = $1', [sourceKey]);
        const sourceDetails = detailsOf(event);
        const normalized = JSON.stringify({ ...sourceDetails, confidence: event.confidence });
        const hash = createHash('sha256').update(JSON.stringify([event.sourceName, event.sourceUrl, normalized])).digest('hex');
        if (source?.hash === hash) {
          await client.query('UPDATE sources SET verified_at = COALESCE($1, verified_at), raw = $2 WHERE source_key = $3',
            [event.verifiedAt, raw, sourceKey]);
          report.unchanged++;
          continue;
        }
        const { rows: [matching] } = await client.query<CanonicalRow>(
          'SELECT id, identity, status_override FROM events WHERE identity = $1', [identity]);
        const previous = source && (await client.query<CanonicalRow>(
          'SELECT id, identity, status_override FROM events WHERE id = $1', [source.event_id])).rows[0];
        const others = previous && (await client.query('SELECT 1 FROM sources WHERE event_id = $1 AND source_key != $2 LIMIT 1',
          [previous.id, sourceKey])).rowCount;
        const existing = matching ?? (others ? undefined : previous);
        const id = existing?.id ?? randomUUID();
        if (!existing) await writeEvent(client, id, identity, sourceDetails);
        await client.query(`INSERT INTO sources (source_key, event_id, name, url, type, hash, verified_at, normalized, raw)
          VALUES (${values(9)}) ON CONFLICT(source_key) DO UPDATE SET event_id=excluded.event_id,
          name=excluded.name, url=excluded.url, hash=excluded.hash, verified_at=COALESCE(excluded.verified_at, sources.verified_at),
          normalized=excluded.normalized, raw=excluded.raw`,
        [sourceKey, id, event.sourceName, event.sourceUrl, event.sourceType, hash, event.verifiedAt, normalized, raw]);
        if (previous && previous.id !== id) {
          if (others) await rebuild(client, previous.id, previous.identity, previous.status_override);
          else {
            await client.query("UPDATE events SET status = 'draft' WHERE id = $1", [previous.id]);
            await change(client, previous.id, actor, 'merged', { into: id });
          }
        }
        await rebuild(client, id, identity, existing?.status_override ?? null);
        await change(client, id, actor, existing ? 'updated' : 'added', { sourceKey, fields: sourceDetails });
        if (existing) report.updated++;
        else report.added++;
      }
      return report;
    });
  }

  async function search(filters: EventFilters = {}, admin?: { status?: EventStatus }): Promise<EventPage> {
    const page = Math.min(10_000, Math.max(1, Math.trunc(filters.page ?? 1)));
    const limit = Math.min(50, Math.max(1, Math.trunc(filters.limit ?? 12)));
    const now = clock().toISOString();
    const conditions = admin ? ['TRUE'] : ["status = 'published'", 'COALESCE(ends_at, starts_at) >= $1'];
    const parameters: (number | string)[] = admin ? [] : [now];
    function add(condition: (slot: string) => string, value: number | string | undefined) {
      if (value !== undefined && value !== '') conditions.push(condition('$' + parameters.push(value)));
    }
    add(slot => `status = ${slot}`, admin?.status);
    add(slot => `city_key = ${slot}`, filters.city && normalizeText(filters.city));
    add(slot => `venue_key = ${slot}`, filters.venue && normalizeText(filters.venue));
    add(slot => `category = ${slot}`, filters.category);
    add(slot => `COALESCE(ends_at, starts_at) >= ${slot}`, filters.from);
    add(slot => `starts_at < ${slot}`, filters.until);
    add(slot => `price_min <= ${slot}`, filters.maxPrice);
    add(slot => `age_limit <= ${slot}`, filters.age);
    const query = normalizeText(filters.query ?? '');
    const ranked = query && (filters.matchWords || filters.sort === 'relevance');
    if (!ranked) {
      for (const term of query.split(' ').filter(Boolean).slice(0, 12)) add(slot => `strpos(search_text, ${slot}) > 0`, term);
    }
    const where = conditions.join(' AND ');
    const whereParameters = [...parameters];
    let order = admin ? 'starts_at DESC, id' : 'starts_at, id';
    if (filters.sort === 'price') order = 'price_min ASC NULLS LAST, ' + order;
    if (filters.sort === 'sessions' || filters.sort === 'family') {
      const family = filters.sort === 'family' ? "(regexp_replace(lower(title), '[^[:alnum:]]+', ' ', 'g') ~ '(^| )(детск|семейн)|(^| )для (детей|малышей)( |$)') DESC, " : '';
      order = family + 'starts_at < $' + parameters.push(filters.from ?? now) + ', ' + order;
    }
    const base = `SELECT ${columns} FROM events WHERE ${where} ORDER BY ${order}`;
    const offset = (page - 1) * limit;
    if (ranked) {
      const { rows } = await pool.query<EventRow>(base, parameters);
      const matched = rows.map(row => ({ row, score: relevance(query, row.title, row.search_text) })).filter(entry => entry.score > 0);
      if (filters.sort === 'relevance') matched.sort((first, second) => second.score - first.score);
      return { events: await eventCards(matched.slice(offset, offset + limit).map(entry => entry.row)), page, limit, total: matched.length };
    }
    const { rows } = await pool.query<EventRow & { total: string }>(
      base.replace(`SELECT ${columns}`, `SELECT ${columns}, count(*) OVER () AS total`) +
      ` LIMIT $${parameters.length + 1} OFFSET $${parameters.length + 2}`, [...parameters, limit, offset]);
    const total = rows[0]?.total ?? (offset ? (await pool.query<{ total: string }>(`SELECT count(*) AS total FROM events WHERE ${where}`,
      whereParameters)).rows[0].total : '0');
    return { events: await eventCards(rows), page, limit, total: Number(total) };
  }

  return {
    search, importEvents,
    async getEvent(id) {
      const { rows } = await pool.query<EventRow>(`SELECT ${columns} FROM events WHERE id = $1 AND status != 'draft'`, [id]);
      return (await eventCards(rows))[0];
    },
    async directories() {
      const { rows } = await pool.query<{ city: string; venue: string }>(`SELECT MIN(city) AS city, MIN(venue) AS venue FROM events
        WHERE status = 'published' AND COALESCE(ends_at, starts_at) >= $1 GROUP BY city_key, venue_key ORDER BY city, venue`, [clock().toISOString()]);
      return {
        cities: Array.from(new Set(rows.map(row => row.city))).sort((first, second) => first.localeCompare(second, 'ru')),
        venues: rows.map(row => ({ city: row.city, name: row.venue })),
        categories: Object.entries(categories).map(([id, label]) => ({ id: id as Category, label })),
      };
    },
    async setStatus(id, status) {
      return transaction(pool, async client => {
        await client.query(lockCatalog);
        const { rows: [event] } = await client.query<{ status: EventStatus; status_override: EventStatus | null }>(
          'SELECT status, status_override FROM events WHERE id = $1', [id]);
        if (event && (event.status !== status || event.status_override !== status)) {
          await client.query('UPDATE events SET status = $1, status_override = $1 WHERE id = $2', [status, id]);
          await change(client, id, 'admin', 'status', { from: event.status, to: status });
        }
        return Boolean(event);
      });
    },
    async eventIdForSource(type, key) {
      return (await pool.query<{ event_id: string }>('SELECT event_id FROM sources WHERE source_key = $1', [type + ':' + key])).rows[0]?.event_id;
    },
    async hasSources() {
      return Boolean((await pool.query('SELECT 1 FROM sources LIMIT 1')).rowCount);
    },
    close: () => pool.end(),
    async subscribe(subscriber, subscription) {
      await pool.query('INSERT INTO subscriptions (subscriber, city, category) VALUES ($1, $2, $3) ON CONFLICT DO NOTHING',
        [subscriber, subscription.city, subscription.category]);
    },
    async subscriptions(subscriber) {
      return (await pool.query<Subscription>('SELECT city, category FROM subscriptions WHERE subscriber = $1 ORDER BY city, category',
        [subscriber])).rows;
    },
    async unsubscribe(subscriber) {
      return (await pool.query('DELETE FROM subscriptions WHERE subscriber = $1', [subscriber])).rowCount ?? 0;
    },
  };
}
